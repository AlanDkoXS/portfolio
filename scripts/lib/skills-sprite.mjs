// Skill icons: the <symbol>s in assets/img/skills/*.svg → a single sprite
// assets/img/skills.svg (one request instead of one per technology). The markup
// uses <use href="/assets/img/skills.svg?v=<hash>#iconX"> (hash set by the generator).

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fail } from './site.mjs';

const BANNER = '<!-- GENERATED by scripts/build-i18n.mjs from assets/img/skills/*.svg — do not edit -->';

/**
 * Merges every <symbol> of the .svg files in `dir` (sorted by file name).
 * Returns the sprite, the set of symbol ids and the sprite version (content hash).
 */
export function buildSkillsSprite(dir) {
  const ids = new Set();
  const symbols = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .flatMap((file) => {
      const svg = fs.readFileSync(path.join(dir, file), 'utf8');
      return [...svg.matchAll(/<symbol\b[\s\S]*?<\/symbol>/g)].map(([symbol]) => {
        const id = symbol.match(/\bid="([^"]+)"/)?.[1];
        if (!id || ids.has(id)) {
          fail(`skills/${file}: <symbol> without an id or with a duplicate id (${id})`);
        }
        ids.add(id);
        return symbol.replace(/>\s+</g, '><').replace(/\s+/g, ' ').trim();
      });
    });
  const sprite =
    `${BANNER}\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join('')}</svg>\n`;
  const version = createHash('sha256').update(sprite).digest('hex').slice(0, 8);
  return { sprite, ids, version };
}

/**
 * Sprite version in the URL (?v=hash): /assets/img/* is cached for up to a day,
 * so a new icon doesn't stay invisible because of an old cached sprite.
 */
export const setSpriteVersion = (html, version) =>
  html.replace(/\/assets\/img\/skills\.svg(?:\?v=\w+)?#/g, `/assets/img/skills.svg?v=${version}#`);

/** Ids the markup references that are not in the sprite (each one once) */
export const unknownSpriteIds = (html, ids) => [
  ...new Set(
    [...html.matchAll(/\/assets\/img\/skills\.svg(?:\?v=\w+)?#([\w-]+)/g)]
      .map(([, id]) => id)
      .filter((id) => !ids.has(id)),
  ),
];
