// Sección "Designs" del home a partir de scripts/data/dribbble.json
// (generado por scripts/build-dribbble.mjs). Sin shots, la sección no se pinta.

import fs from 'node:fs';

const escapeText = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escapeAttr = (s) => escapeText(s).replace(/"/g, '&quot;');

const START = '<!-- dribbble:start (generated by scripts/build-i18n.mjs from scripts/data/dribbble.json) -->';
const MARKER_RE = /<!-- dribbble:start[\s\S]*?<!-- dribbble:end -->/;

export function designsSection({ profile, shots = [] } = {}) {
  if (!shots.length) return `${START}\n      <!-- dribbble:end -->`;
  const cards = shots
    .map(
      (s) => `          <li class="designs__item">
            <a class="designs__link" href="${escapeAttr(s.url)}" target="_blank" rel="noopener">
              <img class="designs__img" src="${escapeAttr(s.image)}" alt="" width="${s.width}" height="${s.height}" loading="lazy" decoding="async" />
              <span class="designs__caption">${escapeText(s.title)}</span>
            </a>
          </li>`,
    )
    .join('\n');
  return `${START}
      <section id="designs" class="designs section">
        <h2 data-i18n="designsTitle" class="section__title">Designs</h2>
        <p data-i18n="designsDescription" class="designs__description">Designs</p>
        <ul class="designs__grid">
${cards}
        </ul>
        <a data-i18n="designsButton" class="btn btn--primary designs__more" href="${escapeAttr(profile)}" target="_blank" rel="noopener">See more on Dribbble</a>
      </section>
      <!-- dribbble:end -->`;
}

/** Reemplaza el bloque entre los marcadores dribbble:start/end de index.html */
export function injectDesigns(html, dataPath) {
  if (!MARKER_RE.test(html)) return html;
  const data = fs.existsSync(dataPath) ? JSON.parse(fs.readFileSync(dataPath, 'utf8')) : {};
  return html.replace(MARKER_RE, () => designsSection(data));
}
