// Trims Boxicons down to the icons the site actually uses.
//
//   node scripts/build-icons.mjs   # run after using a new bx-* icon
//
// Reads the full CSS and font from scripts/vendor/boxicons/, looks for the
// bx-*, bxs-*, bxl-* classes in the markup and the JS, and generates:
//   - assets/css/vendor/boxicons.min.css  (only @font-face, .bx and those classes)
//   - assets/fonts/boxicons/boxicons.woff2 (subset with those glyphs)
// The subset uses pyftsubset (fonttools) via `uvx`; without uvx, it tries `pyftsubset`.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { ROOT, fail } from './lib/site.mjs';

const vendor = path.join(ROOT, 'scripts/vendor/boxicons');
const fullCss = fs.readFileSync(path.join(vendor, 'boxicons.min.css'), 'utf8');

// Files where icon classes may appear
const sources = [
  'index.html',
  'resume.html',
  ...fs.readdirSync(path.join(ROOT, 'scripts/lib')).map((f) => `scripts/lib/${f}`),
  ...fs.readdirSync(path.join(ROOT, 'scripts/data')).map((f) => `scripts/data/${f}`),
];
const walk = (dir) =>
  fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(`${dir}/${e.name}`) : e.name.endsWith('.js') ? [`${dir}/${e.name}`] : [],
  );
sources.push(...walk('assets/js'));

const used = new Set();
for (const file of sources) {
  const text = fs.readFileSync(path.join(ROOT, file), 'utf8');
  for (const [name] of text.matchAll(/\bbx[sl]?-[a-z0-9-]+\b/g)) used.add(name);
}

// Rules of the full CSS: "selector{body}" (no nesting, except @keyframes)
const rules = [...fullCss.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, sel, body]) => ({
  selectors: sel.split(',').map((s) => s.trim()),
  body,
}));
const keyframes = Object.fromEntries(
  [...fullCss.matchAll(/@keyframes ([\w-]+)\{((?:[^{}]*\{[^{}]*\})*)\}/g)].map(([all, name]) => [name, all]),
);

const out = [];
const codepoints = new Set();
const anims = new Set();
const missing = [];
for (const name of [...used].sort()) {
  const glyph = rules.find((r) => r.selectors.includes(`.${name}:before`));
  if (glyph) {
    out.push(`.${name}:before{${glyph.body}}`);
    const cp = glyph.body.match(/content:"\\([0-9a-f]+)"/i);
    if (cp) codepoints.add(`U+${cp[1].toUpperCase()}`);
    continue;
  }
  // Utility classes (bx-spin, bx-sm, …)
  const util = rules.find((r) => r.selectors.includes(`.${name}`));
  if (util) {
    out.push(`.${name}{${util.body}}`);
    for (const [, a] of util.body.matchAll(/(?:^|;)animation:([\w-]+)/g)) anims.add(a);
    continue;
  }
  missing.push(name);
}

if (missing.length) fail(`bx-* classes with no rule in Boxicons: ${missing.join(', ')}`);

const base = rules.find((r) => r.selectors.includes('.bx'));
const css =
  '/* GENERATED by scripts/build-icons.mjs — Boxicons 2.1.4 (MIT), only the icons in use */\n' +
  "@font-face{font-family:boxicons;font-weight:400;font-style:normal;font-display:block;src:url(/assets/fonts/boxicons/boxicons.woff2) format('woff2')}" +
  `.bx{${base.body}}` +
  [...anims].map((a) => keyframes[a]).join('') +
  out.join('') +
  '\n';

fs.mkdirSync(path.join(ROOT, 'assets/css/vendor'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'assets/css/vendor/boxicons.min.css'), css);

// Font subset
const fontOut = path.join(ROOT, 'assets/fonts/boxicons/boxicons.woff2');
fs.mkdirSync(path.dirname(fontOut), { recursive: true });
const args = [
  path.join(vendor, 'boxicons.woff2'),
  `--unicodes=${[...codepoints].join(',')}`,
  '--flavor=woff2',
  '--layout-features=',
  '--no-hinting',
  '--desubroutinize',
  `--output-file=${fontOut}`,
];
try {
  execFileSync('uvx', ['--from', 'fonttools[woff]', 'pyftsubset', ...args], { stdio: 'inherit' });
} catch {
  execFileSync('pyftsubset', args, { stdio: 'inherit' });
}

console.log(
  `Boxicons: ${codepoints.size} icons → CSS ${css.length} B, font ${fs.statSync(fontOut).size} B`,
);
