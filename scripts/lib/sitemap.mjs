// Sitemap entries for the project pages (with hreflang alternates): the block
// between <!-- projects:start/end --> in sitemap.xml.

import { LANGS, SITE, projectPath } from './site.mjs';

const MARKER_RE = / {4}<!-- projects:start[\s\S]*?<!-- projects:end -->/;

function projectEntries(project, today) {
  const alt = LANGS.map(
    (l) => `        <xhtml:link rel="alternate" hreflang="${l}" href="${SITE}${projectPath(project, l)}" />`,
  )
    .concat(`        <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}${projectPath(project, LANGS[0])}" />`)
    .join('\n');
  return LANGS.map(
    (lang) => `    <url>
        <loc>${SITE}${projectPath(project, lang)}</loc>
${alt}
        <lastmod>${today}</lastmod>
        <changefreq>yearly</changefreq>
        <priority>0.7</priority>
    </url>`,
  );
}

/**
 * Returns sitemapXml with the projects block rewritten (appended before
 * </urlset> if the markers are not there yet). `today` is the <lastmod> date
 * (YYYY-MM-DD). Pure: no file access.
 */
export function withProjectEntries(sitemapXml, projects, today) {
  const entries = projects.flatMap((project) => projectEntries(project, today)).join('\n');
  const block = `    <!-- projects:start (generated by scripts/build-i18n.mjs) -->\n${entries}\n    <!-- projects:end -->`;
  return MARKER_RE.test(sitemapXml)
    ? sitemapXml.replace(MARKER_RE, block)
    : sitemapXml.replace('</urlset>', `${block}\n</urlset>`);
}
